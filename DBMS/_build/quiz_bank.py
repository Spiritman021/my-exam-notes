"""DBMS question bank for the chapter-wise / mixed mock test (build_quiz.py).

Q(sec, level, kind, question, right, [4 wrong], explanation)
    Options are shuffled for every attempt. "All of the above" / "None of these" style options stay last.
F(sec, level, kind, question, [5 options in fixed order], index of right option, explanation)
    For statement and assertion-reason questions, where the option order carries meaning.

sec   = notes subtopic, e.g. '1.4' (links to 01-….html#s4 from the solutions)
level = 'E' easy (direct recall) · 'M' medium (apply / distinguish) · 'H' hard (multi-statement, traps)
kind  = Concept, Definition, Scenario, Statement, Not / odd one out, Match, Assertion–Reason, Numerical, Fill in the blank
Add questions only at the end of a chapter's list: each question's id is its position, and saved attempts refer to ids.
"""

def Q(sec, level, kind, q, right, wrong, e):
    assert len(wrong) == 4 and right not in wrong, q
    return {'sec': sec, 'lv': level, 'k': kind, 'q': q, 'o': [right] + wrong, 'a': 0, 'fix': False, 'e': e}

def F(sec, level, kind, q, opts, ans, e):
    assert len(opts) == 5 and 0 <= ans < 5, q
    return {'sec': sec, 'lv': level, 'k': kind, 'q': q, 'o': opts, 'a': ans, 'fix': True, 'e': e}

